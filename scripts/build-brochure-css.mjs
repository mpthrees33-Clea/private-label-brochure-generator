// Compile the brochure Tailwind stylesheet into a TS module the PDF
// renderer can inline. Chromium then needs no request back to the app
// for CSS or for DM Sans (the faces are base64'd into the same module).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(root, "src/lib/pdf/brochure-entry.css");
const outTs = join(root, "src/lib/pdf/brochure-print-css.ts");
const tmpCss = join(tmpdir(), "qfb-brochure-print.css");

execFileSync(
  "npx",
  ["tailwindcss", "-i", entry, "-o", tmpCss, "--minify"],
  { cwd: root, stdio: "inherit" },
);

const faces = [
  ["400", "dm-sans-latin-400-normal.woff2"],
  ["500", "dm-sans-latin-500-normal.woff2"],
  ["600", "dm-sans-latin-600-normal.woff2"],
  ["700", "dm-sans-latin-700-normal.woff2"],
];

const fontCss = faces
  .map(([weight, file]) => {
    const bytes = readFileSync(join(root, "src/lib/pdf/fonts", file));
    const b64 = bytes.toString("base64");
    return `@font-face{font-family:"DM Sans";font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${b64}) format("woff2");}`;
  })
  .join("");

const css = fontCss + readFileSync(tmpCss, "utf8");
const moduleSrc =
  "// Generated by scripts/build-brochure-css.mjs. Do not edit by hand.\n" +
  `export const BROCHURE_PRINT_CSS = ${JSON.stringify(css)};\n`;
writeFileSync(outTs, moduleSrc);
console.log(`wrote ${outTs} (${moduleSrc.length} bytes)`);
